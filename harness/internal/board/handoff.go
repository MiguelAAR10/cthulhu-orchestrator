package board

import (
	"fmt"
	"strings"
	"time"

	"orq/internal/stops"
)

// HandoffInput reúne lo que necesita HANDOFF.md; la CLI lo llena desde .orq.
type HandoffInput struct {
	Now       time.Time
	Root      string // raíz del repo: se quita de cualquier ruta
	Goal      string // primer ítem de memoria cat=requisito
	Board     Board
	Active    []string // "S-04 · título · listas: T1, T3"
	SyncMode  string
	SyncCmds  []string
	Decisions []string // últimas 5 decisiones, ya formateadas
}

const MaxHandoffLines = 120

// clean quita la raíz del repo, cambia otras rutas absolutas por [path] y tapa lo que parezca secreto.
func clean(s, root string) string {
	if root != "" {
		s = strings.ReplaceAll(s, root+"/", "")
		s = strings.ReplaceAll(s, root, ".")
	}
	f := strings.Fields(s)
	changed := false
	for i, tok := range f {
		t := strings.Trim(tok, "\"'`()[]{}<>,;:")
		switch {
		case strings.HasPrefix(t, "/") && strings.Count(t, "/") > 1:
			f[i], changed = "[path]", true
		case stops.LooksSecret(tok):
			f[i], changed = "[redacted]", true
		}
	}
	if !changed {
		return s
	}
	lead := s[:len(s)-len(strings.TrimLeft(s, " "))]
	return lead + strings.Join(f, " ")
}

// Handoff escribe la página para retomar el proyecto: 6 secciones, ≤120 líneas.
func Handoff(in HandoffInput) string {
	var l []string
	add := func(s ...string) { l = append(l, s...) }
	add(fmt.Sprintf("<!-- generated by orq at %s; do not edit -->", in.Now.UTC().Format(time.RFC3339)), "# Handoff", "")
	add("## 1. What this is")
	if in.Goal == "" {
		add("unknown: no requirement saved in memory yet (`orq mem add --cat requisito ...`).")
	} else {
		add(in.Goal)
	}
	add("", "## 2. Status")
	txt := strings.Split(strings.TrimRight(Text(in.Board, false), "\n"), "\n")
	if len(txt) > 55 {
		txt = append(txt[:55], fmt.Sprintf("... (%d more lines: run `orq board`)", len(txt)-55))
	}
	add("```")
	add(txt...)
	add("```", "", "## 3. Open stoppers")
	if len(in.Board.Stoppers) == 0 {
		add("None.")
	}
	for i, s := range in.Board.Stoppers {
		if i == 10 {
			add(fmt.Sprintf("- +%d more: `orq stop list --open`", len(in.Board.Stoppers)-10))
			break
		}
		add(fmt.Sprintf("- %s [%s] %s %s: %s", s.ID, s.Severity, s.Slice, s.Type, s.Text))
	}
	add("", "## 4. How to resume", "1. `orq revive ROLE` (compact context pack for atena, orquestador, planificador...: slice, plan, stoppers, last receipt, channel, memory)", "2. `orq board` (where things stand)")
	if len(in.Active) == 0 {
		add("3. No open slice: start from the next approved story.")
	}
	for i, a := range in.Active {
		if i == 4 {
			break
		}
		add(fmt.Sprintf("%d. %s", i+3, a))
	}
	add("", "## 5. Where memory lives", "Sync mode: `"+in.SyncMode+"`")
	for _, c := range in.SyncCmds {
		add("- " + c)
	}
	add("", "## 6. Last decisions")
	if len(in.Decisions) == 0 {
		add("None recorded.")
	}
	for _, d := range in.Decisions {
		add("- " + d)
	}
	for i := range l {
		l[i] = clean(l[i], in.Root)
	}
	if len(l) > MaxHandoffLines {
		l = append(l[:MaxHandoffLines-1], "... (truncated to 120 lines)")
	}
	return strings.Join(l, "\n") + "\n"
}
