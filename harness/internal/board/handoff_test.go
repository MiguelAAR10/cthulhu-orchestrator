package board

import (
	"strings"
	"testing"

	"orq/internal/stops"
)

// Spec worker-state, acceptance 6 (render): 6 sections, no secret-looking text, ≤120 lines.
func TestHandoffSectionsAndClean(t *testing.T) {
	orq := t.TempDir()
	stops.Add(stops.Path(orq), stops.Raise{Type: "api_key", Severity: "blocking", Slice: "S-01", By: "w", Text: "Need the Stripe key in STRIPE_TEST_KEY"}, now)
	b, _ := Build(orq, now)
	var dec []string
	for i := 0; i < 5; i++ {
		dec = append(dec, "use Postgres")
	}
	out := Handoff(HandoffInput{Now: now, Root: "/home/x/repo", Goal: "Shop owners sell online; see /home/x/repo/docs/a.md and /etc/secret/x token Zq8vR2mX9kLp4TnW7sYb3HcF",
		Board: b, SyncMode: "local", SyncCmds: []string{"stay local"}, Decisions: dec, Active: []string{"S-01 · pay · ready: T1"}})
	for _, h := range []string{"generated by orq at", "## 1. What this is", "## 2. Status", "## 3. Open stoppers", "## 4. How to resume", "## 5. Where memory lives", "## 6. Last decisions", "orq revive", "ST-0001"} {
		if !strings.Contains(out, h) {
			t.Errorf("missing %q", h)
		}
	}
	if stops.LooksSecret(out) || strings.Contains(out, "/home/x") || strings.Contains(out, "/etc/secret") {
		t.Fatal(out)
	}
	if n := strings.Count(out, "\n"); n > MaxHandoffLines {
		t.Fatalf("%d lines", n)
	}
}
